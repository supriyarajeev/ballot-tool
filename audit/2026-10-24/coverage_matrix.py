"""Nine-county local contest coverage matrix (Oct 24, 2026). Run from the repo root after the merge.
Reads the county research files, the merge report and the published data; writes COVERAGE-MATRIX.md."""
import json, glob
J = {j['id']: j for j in json.load(open('data/jurisdictions.json'))['jurisdictions']}
C = json.load(open('data/2026-11-03/contests.json'))['contests']
REP = json.load(open('audit/2026-10-24/local-contests-merge-report.json'))
FILES = {}
for f in sorted(glob.glob('audit/2026-10-24/local-contests/*.json')):
    R = json.load(open(f))
    for cty in R['county'].split('+'): FILES[cty] = (f, R)
HOW = {
    'ca-alameda': "Registrar's online candidate list (search form), read twice in a browser by a research agent; both readings matched",
    'ca-sf': "Department of Elections candidate page and Voter Information Pamphlet; all 11 contests were already in the guide",
    'ca-contra-costa': "Contests On Ballot list (Aug 27) and Candidate List (Aug 14), PDFs read by the project lead in a browser with pdf.js; the two lists agree on every on-ballot contest",
    'ca-marin': "County candidate list read twice by a research agent; both readings matched except where noted",
    'ca-napa': "County candidate list read twice by a research agent",
    'ca-san-mateo': "County candidate roster (printed Sept 3) read twice by a research agent",
    'ca-santa-clara': "Final Qualified List of Local Eligible Candidates (On Ballot Yes/No) read by the project lead in a browser with pdf.js; contests agree with the county's write-in list",
    'ca-solano': "Candidate Filed Log (as of Aug 20) read once by the project lead in a browser with pdf.js",
    'ca-sonoma': "County 'Local Candidates Who Filed' list read twice by a research agent; two fire district contests are from that filing list only",
}
def county_of(j):
    while j and j['type'] != 'county': j = J.get(j.get('parent'))
    return j['id'] if j else None
order = ['ca-alameda', 'ca-contra-costa', 'ca-marin', 'ca-napa', 'ca-sf', 'ca-san-mateo', 'ca-santa-clara', 'ca-solano', 'ca-sonoma']
L = ["# Local contest coverage, nine Bay Area counties (October 24, 2026)", "",
     "Generated by `audit/2026-10-24/coverage_matrix.py` from the county research files in `local-contests/`, the merge report and the published data.", "",
     "\"Confirmed\" means the contest is on the county's official list of contests on the ballot (or its final qualified list marked On Ballot). \"Pending\" means it comes from a filing list or a secondary source. Nothing here has been checked by a person against a sample ballot.", "",
     "| County | Local contests listed | Candidates | Confirmed | Pending | Added Oct 24 | Seats not on the ballot (listed) | Places checked | Status |",
     "|---|---:|---:|---:|---:|---:|---:|---:|---|"]
detail = []
tot = [0] * 6
for cty in order:
    cs = [c for c in C if J.get(c['jurisdiction']) and J[c['jurisdiction']]['type'] not in ('state', 'state-district', 'region') and (county_of(J[c['jurisdiction']]) == cty or cty in (J[c['jurisdiction']].get('counties') or []))]
    nc = sum(len(c.get('candidates', [])) for c in cs)
    conf = sum(1 for c in cs if c.get('listStatus') == 'confirmed'); pend = sum(1 for c in cs if c.get('listStatus') == 'pending')
    older = len(cs) - conf - pend
    r = REP.get(cty, {}); f, R = FILES.get(cty, (None, {}))
    nob = len(J[cty].get('notOnBallot', []))
    status = "Collected from the official list" + ("; some contests pending" if pend else "")
    L.append(f"| {J[cty]['name']} | {len(cs)} | {nc} | {conf} | {pend} | {r.get('added', 0)} | {nob} | {len(R.get('jurisdictionsChecked', []))} | {status} |")
    for i, v in enumerate([len(cs), nc, conf, pend, r.get('added', 0), nob]): tot[i] += v
    detail += [f"## {J[cty]['name']}", "",
               f"- **How it was read.** {HOW[cty]}.",
               f"- **Official sources.** " + "; ".join(f"[{s['label']}]({s['url']})" for s in R.get('officialSources', [])[:3]) + ".",
               f"- **Contests.** {len(cs)} local contests with {nc} candidates. {conf} confirmed, {pend} pending" + (f", {older} added before Oct 24 from city clerk, district or Department of Elections pages (no list status recorded)" if older else "") + ".",
               f"- **Duplicates removed in the merge.** {r.get('duplicates', 0) + r.get('skippedExisting', 0)}" + (": " + "; ".join(r['sameAs']) if r.get('sameAs') else "") + ".",
               f"- **Not on the ballot.** {nob} seats or contests, listed on the county page with their source.",
               "- **Could not be verified.** " + (" ".join(R.get('unavailable', [])) or "Nothing recorded."), ""]
L.append(f"| **Total** | {tot[0]} | {tot[1]} | {tot[2]} | {tot[3]} | {tot[4]} | {tot[5]} | | |")
L += ["", "Contests that cross county lines are counted in each county they cover, so the total counts some contests more than once. "
      f"The guide has {sum(1 for c in C if J.get(c['jurisdiction']) and J[c['jurisdiction']]['type'] not in ('state', 'state-district', 'region'))} distinct local contests.", ""] + detail
open('audit/2026-10-24/COVERAGE-MATRIX.md', 'w').write('\n'.join(L) + '\n')
print('\n'.join(L[6:18]))
