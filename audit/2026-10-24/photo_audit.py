"""Candidate photo audit (Oct 24, 2026). Run from the repo root: python3 audit/2026-10-24/photo_audit.py
Checks every candidate record against assets/candidates/: file exists, 192x192, no duplicate images, no orphan files,
every shown photo has source, license, license link, credit, identity check and permission basis. Writes PHOTO-AUDIT.md."""
import json, hashlib, os, collections
from PIL import Image
D = json.load(open('data/2026-11-03/candidates.json'))['candidates']
C = {c['id']: c for c in json.load(open('data/2026-11-03/contests.json'))['contests']}
M = {r['candidateId']: r for r in json.load(open('audit/2026-10-24/photo-manifest.json'))['candidates']}
files = sorted(f for f in os.listdir('assets/candidates') if f.endswith(('.jpg', '.png', '.webp')))
used, problems, hashes, rows = set(), [], collections.defaultdict(list), []
leg = lambda ph: 'does not cover the Legislature' in (ph.get('permission') or {}).get('evidence', '')
for c in D:
    ph = c.get('photo')
    con = C.get(c['contest'], {})
    if c['contest'] not in C or c['id'] not in con.get('candidates', []): problems.append(f"{c['id']}: contest reference does not resolve")
    if not ph:
        rows.append((c, None, 'Placeholder (initials)', M.get(c['id'], {}).get('status', '')))
        continue
    p = ph['src']; used.add(os.path.basename(p))
    if not os.path.exists(p): problems.append(f"{c['id']}: file {p} missing"); continue
    im = Image.open(p)
    if im.size != (192, 192): problems.append(f"{c['id']}: {p} is {im.size}, expected 192x192")
    h = hashlib.sha256(open(p, 'rb').read()).hexdigest(); hashes[h].append(c['id'])
    for k in ('sourceUrl', 'sourcePage', 'license', 'licenseUrl', 'credit', 'identityCheck', 'retrieved', 'modified'):
        if not ph.get(k): problems.append(f"{c['id']}: photo missing {k}")
    if not (ph.get('permission') or {}).get('evidence'): problems.append(f"{c['id']}: photo missing permission basis")
    concern = 'Legal basis not settled (PD-CAGov on a Legislature photo)' if leg(ph) else ('Relies on Commons PD-CAGov reading' if 'PD-CAGov' in ph['license'] else '')
    rows.append((c, ph, 'Photo shown', concern))
for h, ids in hashes.items():
    if len(ids) > 1: problems.append('Duplicate image used for ' + ', '.join(ids))
orphans = [f for f in files if f not in used]
shown = [r for r in rows if r[1]]
n = len(D)
L = ["# Candidate photo coverage and rights audit (October 24, 2026)", "",
     "Generated by `audit/2026-10-24/photo_audit.py` from candidates.json, contests.json, assets/candidates and photo-manifest.json.", "",
     "| Measure | Count |", "|---|---|",
     f"| Candidate records reviewed | {n} |",
     f"| Photos shown (source, license and identity recorded) | {len(shown)} |",
     f"| Of those, legal basis not settled (Legislature PD-CAGov) | {sum(1 for r in shown if r[3].startswith('Legal'))} |",
     f"| Of those, relying on Commons' PD-CAGov reading for other government works | {sum(1 for r in shown if r[3].startswith('Relies'))} |",
     f"| Of those, federal public domain, CC0 or Creative Commons | {sum(1 for r in shown if not r[3])} |",
     f"| Found but not used (identity not confirmed, license doubtful, Legislature portrait or too small) | {sum(1 for r in rows if not r[1] and ('doubtful' in r[3] or 'another person' in r[3] or 'found, not used' in r[3] or 'photo removed' in r[3]))} |",
     f"| Local candidates not searched one by one (Oct 24 county lists) | {sum(1 for r in rows if not r[1] and 'not searched individually' in r[3])} |",
     f"| Placeholders (initials) | {n - len(shown)} |",
     f"| No reliable reusable image found in the Oct 24 Wikidata and Commons search | {sum(1 for r in rows if not r[1] and 'no reusable' in r[3])} |",
     f"| Broken, mismatched-size or duplicate images | {len(problems)} |",
     f"| Image files without a record (orphans) | {len(orphans)} |",
     f"| Coverage | {100 * len(shown) / n:.1f}% ({len(shown)} of {n}) |", "",
     "Coverage counts a photo as usable when it has a recorded license tag, credit, source and identity check. It does not mean a lawyer has cleared it; see the concerns column.", "",
     "## Problems found by the script", ""] + ([f"- {p}" for p in problems] or ["- None."]) + ["", "## Orphan files", ""] + ([f"- {o}" for o in orphans] or ["- None."]) + [
     "", "## Photos shown", "", "| Candidate | Contest | License | Rights concern |", "|---|---|---|---|"] + [
     f"| {r[0]['name']} | {C.get(r[0]['contest'], {}).get('office', '')}{', ' + C[r[0]['contest']]['district'] if C.get(r[0]['contest'], {}).get('district') else ''} | {r[1]['license']} | {r[3] or 'None recorded'} |" for r in shown] + [
     "", "## Not used", "", "- Official voter guide candidate photos: no license is given, so they are not reused.",
     "- Campaign websites and social media: not searched for licenses in this release; public visibility is not permission.",
     "- Gloria Romero's Commons file: labeled CC BY-SA 2.0 but sourced from a news site, so the license is doubtful.",
     "- 19 Legislature portraits removed on Oct 24, 2026 (PD-CAGov does not cover the Legislature); see photos-removed-legislature.json.", ""] + [
     f"- {r[0]['name']} ({r[3]}): {M[r[0]['id']].get('note', '')}" for r in rows if not r[1] and 'found, not used' in r[3]] + [""]
open('audit/2026-10-24/PHOTO-AUDIT.md', 'w').write('\n'.join(L))
print('\n'.join(L[4:20])); print('problems', problems, 'orphans', orphans)
