// Generates the audit and coverage documents in docs/ from the data, so they never drift from it.
//   node tools/report.mjs
// Writes: docs/JURISDICTION-INVENTORY.md, docs/COVERAGE-REPORT.md, docs/SOURCE-REGISTER.md,
//         docs/EVIDENCE-LEDGER.md, docs/MEASURE-AUDIT.md, docs/CANDIDATE-AUDIT.md
// Run tools/build-ledger.mjs first so sources.json and evidence.json are current (npm run build does both).
//   node tools/report.mjs [--root <dir>]     --root writes the docs of a copy (used by npm run check)
// Every number and status in these docs is computed from data. Hand-written observations from the
// October 22, 2026 audit are kept in clearly labeled sections and contain no counts (VAL-10).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ri = process.argv.indexOf("--root");
const root = ri > 0 ? path.resolve(process.argv[ri + 1]) : path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const rdOpt = (p) => (fs.existsSync(path.join(root, p)) ? JSON.parse(fs.readFileSync(path.join(root, p), "utf8")) : null);
const words = ["zero", "one", "two", "three", "four", "five", "six", "seven", "eight", "nine", "ten", "eleven", "twelve"];
const word = (n) => words[n] || String(n);
const list = (a) => (a.length <= 1 ? a.join("") : a.slice(0, -1).join(", ") + " and " + a[a.length - 1]);
const rd = (p) => JSON.parse(fs.readFileSync(path.join(root, p), "utf8"));
const out = (name, text) => fs.writeFileSync(path.join(root, "docs", name), text.trim() + "\n");
const cell = (v) => String(v ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");
const row = (a) => "| " + a.map(cell).join(" | ") + " |";
const table = (head, rows) => [row(head), row(head.map(() => "---")), ...rows.map(row)].join("\n");
const count = (arr, f) => arr.reduce((m, x) => ((m[f(x)] = (m[f(x)] || 0) + 1), m), {});
const GEN = "_Generated by `tools/report.mjs` from the files in `data/`. Do not edit by hand; edit the data and rerun._";

const election = rd("data/elections.json").elections.find((e) => e.status === "current");
const jur = rd("data/jurisdictions.json").jurisdictions;
const J = new Map(jur.map((j) => [j.id, j]));
const measures = election.files.measures.flatMap((p) => rd(p).items);
const contests = rd(election.files.contests).contests;
const candidates = rd(election.files.candidates).candidates;
const C = new Map(candidates.map((c) => [c.id, c]));
const sources = rd("data/sources.json").sources;
const evidence = rd("data/evidence.json").evidence;
const counties = jur.filter((j) => j.type === "county").sort((a, b) => a.name.localeCompare(b.name));
const region = rdOpt("data/region.json");
const bayIds = region ? region.counties : counties.filter((c) => c.region === "bay-area").map((c) => c.id);
const bay = counties.filter((c) => bayIds.includes(c.id));
const others = counties.filter((c) => !bayIds.includes(c.id));
const candidateOrder = rdOpt("tests/fixtures/candidate-order.json");

// Cycle-safe parent walk (VAL-01).
const countyOf = (j) => { const seen = new Set(); while (j && !seen.has(j.id)) { seen.add(j.id); if (j.type === "county") return j; if (j.type === "state" || j.type === "region" || j.type === "state-district") return null; j = J.get(j.parent); } return null; };
const citiesIn = (cid) => jur.filter((j) => j.type === "city" && j.parent === cid);
const short = (c) => c.name.replace(/ County$/, "").replace(/ \(City and County\)$/, "");
const inCounty = (jid, cid) => { const j = J.get(jid); if (!j || j.type === "state") return false; if (j.type === "region" || j.type === "state-district") return (j.counties || []).includes(cid); return (countyOf(j) || {}).id === cid || (j.counties || []).includes(cid); };
const nM = (cid) => measures.filter((m) => inCounty(m.jurisdiction, cid)).length;
const nC = (cid) => contests.filter((c) => inCounty(c.jurisdiction, cid)).length;
const INV = { "not-collected": "Not collected", partial: "Partly collected", collected: "Collected, not reconciled", reconciled: "Reconciled", "none-found-confirmed": "None found (confirmed)" };
const LABEL = { verified: "Verified", "needs-review": "Needs review", incomplete: "Incomplete (required info or evidence is missing)", "source-unavailable": "Source unavailable", "not-researched": "Not yet researched", "not-applicable": "Not applicable", archived: "Archived", superseded: "Superseded" };
const st = (arr) => Object.entries(count(arr, (x) => x.status)).map(([k, v]) => `${LABEL[k] || k} ${v}`).join(", ");

